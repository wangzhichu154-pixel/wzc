"""Measure real C++ replay processes; no exchange or tick-to-trade claim."""
import argparse
import datetime
import hashlib
import json
import math
import platform
import os
import subprocess
import time
from pathlib import Path

def sha256_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as source:
        for block in iter(lambda: source.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()

def histogram(values):
    values = sorted(values)
    def q(p):
        return values[min(len(values) - 1, math.ceil(p * len(values)) - 1)]
    return dict(count=len(values), p50=q(.5), p90=q(.9), p99=q(.99), p99_9=q(.999), max=values[-1])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', required=True)
    parser.add_argument('--input', required=True)
    parser.add_argument('--runs', type=int, default=30)
    args = parser.parse_args()
    if not 2 <= args.runs <= 10000:
        parser.error('runs must be between 2 and 10000')
    binary = Path(args.binary).resolve()
    capture = Path(args.input).resolve()
    times, internal, throughput, checksums, failures = [], [], [], set(), []
    for index in range(args.runs):
        start = time.perf_counter_ns()
        try:
            proc = subprocess.run([str(binary), '--input', str(capture)], text=True, capture_output=True, timeout=120)
            total = time.perf_counter_ns() - start
            if proc.returncode:
                failures.append(dict(run=index, code=proc.returncode, error=proc.stderr[-2000:]))
                continue
            result = json.loads(proc.stdout)
            times.append(total)
            internal.append(result['elapsed_ns'])
            throughput.append(result['messages'] * 1e9 / max(1, result['elapsed_ns']))
            checksums.add(result['checksum'])
        except (subprocess.TimeoutExpired, ValueError, KeyError) as error:
            failures.append(dict(run=index, error=str(error)))
    report = {
        'measurement': 'whole_file_replay_not_tick_to_trade',
        'measured_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'platform': platform.platform(),
        'processor': platform.processor(),
        'logical_cpus_visible': os.cpu_count(),
        'binary_sha256': sha256_file(binary),
        'workload': 'Capture as supplied; synthetic only if generated by tests/make_fixture.py',
        'input_sha256': sha256_file(capture),
        'input_bytes': capture.stat().st_size,
        'requested_runs': args.runs,
        'failures': failures,
        'deterministic': len(checksums) == 1 and not failures,
        'tail_resolution_warning': 'P99.9 requires substantially more independent samples than this default run count.',
    }
    try:
        cpuinfo = Path('/proc/cpuinfo').read_text()
        report['processor'] = next(line.split(':', 1)[1].strip() for line in cpuinfo.splitlines() if line.startswith('model name'))
    except (OSError, StopIteration):
        pass
    if times:
        report.update(process_latency_ns=histogram(times), internal_file_latency_ns=histogram(internal), messages_per_second=histogram(throughput))
    print(json.dumps(report, indent=2))
    return int(bool(failures) or len(checksums) != 1)

if __name__ == '__main__':
    raise SystemExit(main())
